"""Regenerates crates/rxui/src/icons/lucide.rs from an extracted lucide-static package.

Usage: python3 -I lucide_icons.py <package-dir> <output.rs>

<package-dir> is the `package` directory of `npm pack lucide-static@<version>`.
Treat it as untrusted data: this script only parses its SVG files and package.json.
"""

import json
import sys
import xml.etree.ElementTree as ET

# Lucide name -> Rust constant, in documentation order.
ICONS = [
    "chevron-up", "chevron-down", "chevron-left", "chevron-right",
    "arrow-up", "arrow-down", "arrow-left", "arrow-right",
    "x", "check", "plus", "minus", "search", "settings",
    "ellipsis", "ellipsis-vertical", "menu",
    "file", "file-text", "folder", "folder-open", "save", "copy", "clipboard",
    "trash", "pencil",
    "eye", "eye-off", "lock", "lock-open", "refresh-cw", "rotate-ccw", "rotate-cw",
    "play", "square", "pause",
    "info", "circle-alert", "triangle-alert", "circle-check", "circle-x",
    "panel-left", "panel-bottom", "columns-2", "list", "layout-grid",
    "funnel", "text-wrap", "terminal", "git-branch", "bug", "external-link",
    "download", "upload", "house", "star",
]
SVG = "{http://www.w3.org/2000/svg}"


def num(value):
    text = f"{float(value):.4f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def points(value):
    nums = value.replace(",", " ").split()
    return [(nums[i], nums[i + 1]) for i in range(0, len(nums), 2)]


def element_path(el):
    tag = el.tag.removeprefix(SVG)
    a = el.attrib
    f = lambda k, d="0": float(a.get(k, d))
    if tag == "path":
        return " ".join(a["d"].split())
    if tag == "line":
        return f"M{num(f('x1'))} {num(f('y1'))}L{num(f('x2'))} {num(f('y2'))}"
    if tag in ("polyline", "polygon"):
        p = points(a["points"])
        d = f"M{num(p[0][0])} {num(p[0][1])}" + "".join(
            f"L{num(x)} {num(y)}" for x, y in p[1:]
        )
        return d + ("Z" if tag == "polygon" else "")
    if tag in ("circle", "ellipse"):
        cx, cy = f("cx"), f("cy")
        rx, ry = (f("r"), f("r")) if tag == "circle" else (f("rx"), f("ry"))
        arc = f"A{num(rx)} {num(ry)} 0 1 0"
        return (
            f"M{num(cx - rx)} {num(cy)}{arc} {num(cx + rx)} {num(cy)}"
            f"{arc} {num(cx - rx)} {num(cy)}Z"
        )
    if tag == "rect":
        x, y, w, h = f("x"), f("y"), f("width"), f("height")
        rx = a.get("rx", a.get("ry"))
        ry = a.get("ry", a.get("rx"))
        rx = min(float(rx or 0), w / 2)
        ry = min(float(ry or 0), h / 2)
        if rx == 0 or ry == 0:
            return f"M{num(x)} {num(y)}H{num(x + w)}V{num(y + h)}H{num(x)}Z"
        c = f"A{num(rx)} {num(ry)} 0 0 1"
        return (
            f"M{num(x + rx)} {num(y)}H{num(x + w - rx)}{c} {num(x + w)} {num(y + ry)}"
            f"V{num(y + h - ry)}{c} {num(x + w - rx)} {num(y + h)}"
            f"H{num(x + rx)}{c} {num(x)} {num(y + h - ry)}"
            f"V{num(y + ry)}{c} {num(x + rx)} {num(y)}Z"
        )
    raise SystemExit(f"unsupported element <{tag}>")


def constant(name):
    return name.upper().replace("-", "_")


def variant(name):
    return "".join(part.capitalize() for part in name.split("-"))


def main(package, output):
    version = json.load(open(f"{package}/package.json"))["version"]
    entries = []
    for name in ICONS:
        root = ET.parse(f"{package}/icons/{name}.svg").getroot()
        if root.get("viewBox") != "0 0 24 24":
            raise SystemExit(f"{name}: unexpected view box")
        d = [element_path(el) for el in root]
        if any('"' in p or "\\" in p for p in d):
            raise SystemExit(f"{name}: unexpected characters")
        entries.append((name, d))
    out = [
        f"// Generated by crates/rxui/tools/lucide_icons.py from lucide-static {version}",
        "// (https://www.npmjs.com/package/lucide-static, https://lucide.dev). Do not edit.",
        "// Lucide is ISC licensed, with icons derived from Feather under MIT; see",
        "// LICENSE-lucide.txt. Shapes other than <path> are converted to path data.",
        "",
        "/// A built-in icon, indexing [`DATA`].",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
        "pub(super) enum Builtin {",
    ]
    out += [f"    {variant(n)}," for n, _ in entries]
    out += [
        "}",
        "impl Builtin {",
        "    /// Every built-in icon, in [`DATA`] order.",
        f"    pub(super) const ALL: [Self; {len(entries)}] = [",
    ]
    out += [f"        Self::{variant(n)}," for n, _ in entries]
    out += [
        "    ];",
        "}",
        "",
        "/// Lucide name and the SVG path data of each shape of each built-in icon,",
        "/// in a 24×24 view box. Shapes are separate: each starts its own path.",
        f"pub(super) const DATA: [(&str, &[&str]); {len(entries)}] = [",
    ]
    for n, d in entries:
        out.append(f'    ("{n}", &[')
        out += [f'        "{p}",' for p in d]
        out.append("    ]),")
    out += ["];", "", "impl super::Icon {"]
    for n, _ in entries:
        out.append(f"    /// Lucide `{n}`.")
        out.append(
            f"    pub const {constant(n)}: Self = Self::builtin(Builtin::{variant(n)});"
        )
    out.append("}")
    with open(output, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
